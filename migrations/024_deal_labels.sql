-- 024_deal_labels.sql
-- Why: approach C builds the Chef's trays in code by grouping this week's
--   gated deals by a generic item ("chicken thighs") and culinary role
--   (protein / vegetable / ...), and compares prices per 100 g / ml when the
--   package size is known. Those labels come from an offline LLM labelling job
--   and must be stored, never derived at request time. Generation also needs to
--   record what the user was offered and kept in the tray carousel, and the
--   validated dish plan, so a plan can be re-scored and label errors found.
-- Design log: (new) "Approach C: code-built trays" --
--   experiments/chef/DESIGN_APPROACH_C.md sections 3 and 9.
--
-- Scope rule (CLAUDE.md, Product framing): item/role labels decide only what
--   is SURFACED (grouping, trays, price comparison), never dietary access.
--   Dietary access stays a lookup of curated product attributes. Labels only
--   ever apply to the already-gated deal set.
--
-- What changes:
--   deal_labels                        new; one row per labelled deal.
--   recipe_generations.offered_deal_ids   deals in the trays at generate time.
--   recipe_generations.kept_deal_ids      what the user kept (offered minus
--                                         kept = carousel rejections).
--   recipe_generations.pantry_product_ids the pantry staples the user confirmed.
--   recipe_generations.dish_plan          the validated dish-first plan.
--
--   deal_labels is keyed by deal_id and cascades with the deal: a deal that is
--   deleted takes its label with it. prompt_version lets the job relabel when
--   the prompt changes (a row at an older version is relabelled in place).
--   size_qty/size_unit are the package size in g, ml or each, NULL when the
--   deal text does not say.
--
-- Idempotent: IF NOT EXISTS throughout. Must apply after 022
--   (recipe_generations). Independent of 023.

BEGIN;

CREATE TABLE IF NOT EXISTS deal_labels (
    deal_id        INTEGER PRIMARY KEY REFERENCES deals(deal_id) ON DELETE CASCADE,
    item           TEXT NOT NULL,
    role           VARCHAR(16) NOT NULL,
    size_qty       NUMERIC(10,2),
    size_unit      VARCHAR(8),
    model          VARCHAR(128) NOT NULL,
    prompt_version VARCHAR(16) NOT NULL,
    labelled_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_deal_labels_role CHECK (role IN (
        'protein', 'vegetable', 'fruit', 'starch', 'dairy', 'pantry_staple',
        'condiment', 'prepared_meal', 'snack', 'beverage', 'non_food', 'unknown')),
    CONSTRAINT chk_deal_labels_size_unit CHECK (
        size_unit IS NULL OR size_unit IN ('g', 'ml', 'each')),
    CONSTRAINT chk_deal_labels_size_pair CHECK (
        (size_qty IS NULL) = (size_unit IS NULL)),
    CONSTRAINT chk_deal_labels_size_positive CHECK (
        size_qty IS NULL OR size_qty > 0)
);

CREATE INDEX IF NOT EXISTS idx_deal_labels_role_item ON deal_labels (role, item);

ALTER TABLE recipe_generations
    ADD COLUMN IF NOT EXISTS offered_deal_ids INTEGER[];
ALTER TABLE recipe_generations
    ADD COLUMN IF NOT EXISTS kept_deal_ids INTEGER[];
ALTER TABLE recipe_generations
    ADD COLUMN IF NOT EXISTS pantry_product_ids INTEGER[];
ALTER TABLE recipe_generations
    ADD COLUMN IF NOT EXISTS dish_plan JSONB;

COMMENT ON TABLE deal_labels IS
    'LLM-derived {item, role, package size} per deal, written by app/services/deal_labeller.py. Decides only what is surfaced in the trays (grouping, price comparison) -- never dietary access, which is decided from curated product attributes.';
COMMENT ON COLUMN recipe_generations.offered_deal_ids IS
    'Deal ids in the trays as rebuilt at generate time; NULL before migration 024.';
COMMENT ON COLUMN recipe_generations.kept_deal_ids IS
    'Deal ids the user kept in the tray carousel; offered minus kept = rejections.';
COMMENT ON COLUMN recipe_generations.pantry_product_ids IS
    'Pantry staple product ids the user confirmed before generation.';
COMMENT ON COLUMN recipe_generations.dish_plan IS
    'The validated dish-first plan (dishes with anchor/side deal ids and pantry product ids, stock-up ids).';

COMMIT;

